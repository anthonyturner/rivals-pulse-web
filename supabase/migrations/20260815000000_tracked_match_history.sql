create table if not exists public.tracked_matches (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players (id) on delete cascade,
  provider text not null,
  match_uid text not null,
  played_at timestamptz,
  raw_payload jsonb not null default '{}'::jsonb,
  performance jsonb,
  recorded_at timestamptz not null default now(),
  unique (player_id, match_uid)
);

create index if not exists tracked_matches_player_played_at_idx
  on public.tracked_matches (player_id, played_at desc);

alter table public.tracked_matches enable row level security;

revoke insert, update, delete on public.tracked_matches from anon, authenticated;

grant select on public.tracked_matches to anon, authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'tracked_matches'
      and policyname = 'Public tracked-match reads'
  ) then
    create policy "Public tracked-match reads"
      on public.tracked_matches for select to anon, authenticated using (true);
  end if;
end
$$;
