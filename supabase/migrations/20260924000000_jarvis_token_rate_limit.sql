-- One row per Jarvis conversation token minted, so `elevenlabs-agent-token` can cap how many a
-- single caller mints per hour (issue 569). The function is reachable by anyone who has the app,
-- and each token opens a session billed to this project's ElevenLabs account.
create table if not exists public.jarvis_token_requests (
  id bigint generated by default as identity primary key,
  client_ip text not null,
  requested_at timestamptz not null default now()
);

create index if not exists jarvis_token_requests_ip_requested_at_idx
  on public.jarvis_token_requests (client_ip, requested_at desc);

alter table public.jarvis_token_requests enable row level security;

-- Unlike the match-history tables, nothing here is ever readable by a client: the rows are IP
-- addresses. With RLS on and no policy, only the service role, which the edge function uses and
-- which bypasses RLS, can read or write it.
revoke all on public.jarvis_token_requests from anon, authenticated;
