-- Home page content for the website, moved from Turso (issue 107). Additive only: it creates two
-- new tables. The home news sync records its runs in `sync_runs` and its official-site snapshot in
-- `external_sources`, both created by 20261030042403_hero_content.sql.
--
-- Nothing here is readable with the publishable key: RLS is on, there is no policy, and only the
-- service role has grants. The website reads and writes through its server.

-- The home page portal cards. `raw_json` is the card the API returns as is; the other columns
-- repeat fields of it. `sort_order` is unique, so it alone fixes the order the API returns (Turso
-- broke ties on the title, which can no longer happen).
create table if not exists public.home_portals (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  path text not null,
  image text not null,
  sort_order integer not null,
  raw_json jsonb not null,
  updated_at timestamptz not null default now(),
  constraint home_portals_sort_order_key unique (sort_order)
);

-- One row per key of the home page content (`latestNews`, `quickLinks`, ...). The home news sync
-- rewrites most of them daily; `heroStats` and `featuredGuides` come from the seed files.
-- `payload` is nullable because a block can be empty: `latestTuning` is null when the official site
-- has no balance post.
create table if not exists public.home_content_blocks (
  content_key text primary key,
  payload jsonb,
  updated_at timestamptz not null default now()
);

alter table public.home_portals enable row level security;
alter table public.home_content_blocks enable row level security;

revoke all on table public.home_portals from anon, authenticated;
revoke all on table public.home_content_blocks from anon, authenticated;

grant select, insert, update, delete on table public.home_portals to service_role;
grant select, insert, update, delete on table public.home_content_blocks to service_role;

revoke all on sequence public.home_portals_id_seq from anon, authenticated;
grant usage, select on sequence public.home_portals_id_seq to service_role;
