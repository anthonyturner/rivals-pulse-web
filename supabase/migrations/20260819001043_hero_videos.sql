create table public.heroes (
  id text primary key,
  name text not null,
  role text not null check (role in ('Vanguard', 'Duelist', 'Strategist', 'Multi-Role')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.hero_videos (
  id bigint generated by default as identity primary key,
  source_key text not null unique,
  hero_id text references public.heroes(id) on update cascade on delete cascade,
  role text check (role in ('Vanguard', 'Duelist', 'Strategist', 'Multi-Role')),
  video_type text not null check (video_type in ('paz-gameplay', 'paz-counters-combos')),
  youtube_id text not null,
  title text not null,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint hero_videos_target_check check ((hero_id is null) <> (role is null))
);

create index hero_videos_hero_id_idx on public.hero_videos (hero_id);
create index hero_videos_role_idx on public.hero_videos (role);
create index hero_videos_type_sort_idx on public.hero_videos (video_type, sort_order);

alter table public.heroes enable row level security;
alter table public.hero_videos enable row level security;

revoke all on table public.heroes from anon, authenticated;
revoke all on table public.hero_videos from anon, authenticated;
grant select on table public.heroes to anon, authenticated;
grant select on table public.hero_videos to anon, authenticated;
grant select, insert, update, delete on table public.heroes to service_role;
grant select, insert, update, delete on table public.hero_videos to service_role;
grant usage, select on sequence public.hero_videos_id_seq to service_role;

create policy "Hero references are publicly readable"
on public.heroes
for select
to anon, authenticated
using (true);

create policy "Hero videos are publicly readable"
on public.hero_videos
for select
to anon, authenticated
using (true);
