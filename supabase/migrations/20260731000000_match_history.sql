create table if not exists public.players (
  id bigint generated by default as identity primary key,
  provider text not null,
  provider_player_uid text not null,
  player_name text not null,
  normalized_name text not null,
  profile jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, provider_player_uid)
);

create index if not exists players_normalized_name_idx
  on public.players (normalized_name);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  provider text not null,
  match_uid text not null,
  played_at timestamptz,
  raw_payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, match_uid)
);

create index if not exists matches_played_at_idx
  on public.matches (played_at desc);

create table if not exists public.player_matches (
  player_id bigint not null references public.players (id) on delete cascade,
  match_id bigint not null references public.matches (id) on delete cascade,
  played_at timestamptz,
  performance jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (player_id, match_id)
);

create index if not exists player_matches_player_played_at_idx
  on public.player_matches (player_id, played_at desc);

create table if not exists public.match_history_sync_state (
  player_id bigint primary key references public.players (id) on delete cascade,
  last_synced_at timestamptz not null,
  last_error text,
  updated_at timestamptz not null default now()
);

alter table public.players enable row level security;
alter table public.matches enable row level security;
alter table public.player_matches enable row level security;
alter table public.match_history_sync_state enable row level security;

revoke insert, update, delete on public.players from anon, authenticated;
revoke insert, update, delete on public.matches from anon, authenticated;
revoke insert, update, delete on public.player_matches from anon, authenticated;
revoke all on public.match_history_sync_state from anon, authenticated;

grant select on public.players to anon, authenticated;
grant select on public.matches to anon, authenticated;
grant select on public.player_matches to anon, authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'players'
      and policyname = 'Public match-history player reads'
  ) then
    create policy "Public match-history player reads"
      on public.players for select to anon, authenticated using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'matches'
      and policyname = 'Public match reads'
  ) then
    create policy "Public match reads"
      on public.matches for select to anon, authenticated using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'player_matches'
      and policyname = 'Public player-match reads'
  ) then
    create policy "Public player-match reads"
      on public.player_matches for select to anon, authenticated using (true);
  end if;
end
$$;
