-- Hero content for the website, moved from Turso (issue 105). Additive only: it creates new tables
-- and one new function and leaves `public.heroes`, which `hero_videos` points at, untouched.
--
-- Nothing here is readable with the publishable key: RLS is on, there is no policy, and only the
-- service role has grants. The website reads and writes through its server.

-- One row per hero. `raw_json` is the record the API returns as is; the other columns repeat
-- fields of it so they can be listed and checked without opening the blob.
create table if not exists public.hero_content (
  id text primary key,
  name text not null,
  role text not null,
  difficulty integer not null,
  summary text not null,
  playstyle text not null,
  image_url text not null,
  raw_json jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.hero_list_items (
  id bigint generated by default as identity primary key,
  hero_id text not null references public.hero_content(id) on update cascade on delete cascade,
  item_type text not null check (item_type in ('strength', 'weakness', 'counter', 'synergy')),
  value text not null,
  sort_order integer not null,
  constraint hero_list_items_position_key unique (hero_id, item_type, sort_order)
);

-- `kit_role` and `kit_label` are null for a hero's own abilities and set for an ability that
-- belongs to a role kit (Deadpool).
create table if not exists public.hero_abilities (
  id bigint generated by default as identity primary key,
  hero_id text not null references public.hero_content(id) on update cascade on delete cascade,
  kit_role text,
  kit_label text,
  name text not null,
  ability_type text not null,
  description text not null,
  technical_details jsonb not null default '[]'::jsonb,
  sort_order integer not null
);

create unique index if not exists hero_abilities_position_key
  on public.hero_abilities (hero_id, coalesce(kit_role, ''), sort_order);

-- One row per run of a scheduled or manual sync. Every web content domain reuses it.
create table if not exists public.sync_runs (
  id bigint generated by default as identity primary key,
  source_key text not null,
  status text not null,
  message text,
  started_at timestamptz not null,
  finished_at timestamptz,
  details jsonb
);

create index if not exists sync_runs_source_key_started_at_idx
  on public.sync_runs (source_key, started_at desc);

-- The last payload a sync fetched from an outside source. The hero syncs keep their roster
-- snapshots here to report what changed since the previous run.
create table if not exists public.external_sources (
  source_key text primary key,
  source_name text not null,
  url text not null,
  payload jsonb not null,
  fetched_at timestamptz not null,
  status text not null,
  error text
);

alter table public.hero_content enable row level security;
alter table public.hero_list_items enable row level security;
alter table public.hero_abilities enable row level security;
alter table public.sync_runs enable row level security;
alter table public.external_sources enable row level security;

revoke all on table public.hero_content from anon, authenticated;
revoke all on table public.hero_list_items from anon, authenticated;
revoke all on table public.hero_abilities from anon, authenticated;
revoke all on table public.sync_runs from anon, authenticated;
revoke all on table public.external_sources from anon, authenticated;

grant select, insert, update, delete on table public.hero_content to service_role;
grant select, insert, update, delete on table public.hero_list_items to service_role;
grant select, insert, update, delete on table public.hero_abilities to service_role;
grant select, insert, update, delete on table public.sync_runs to service_role;
grant select, insert, update, delete on table public.external_sources to service_role;

grant usage, select on sequence public.hero_list_items_id_seq to service_role;
grant usage, select on sequence public.hero_abilities_id_seq to service_role;
grant usage, select on sequence public.sync_runs_id_seq to service_role;

-- Stores one hero and rebuilds its list items and abilities from the same JSON, in one
-- transaction, so the three tables cannot disagree. Every hero writer calls this.
-- A list or ability array that is missing or is not an array counts as empty.
create or replace function public.save_hero(p_hero jsonb)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_id text := p_hero ->> 'id';
begin
  if v_id is null or btrim(v_id) = '' then
    raise exception 'save_hero: the hero has no id';
  end if;

  insert into public.hero_content (
    id, name, role, difficulty, summary, playstyle, image_url, raw_json, updated_at
  )
  values (
    v_id,
    p_hero ->> 'name',
    p_hero ->> 'role',
    (p_hero ->> 'difficulty')::integer,
    p_hero ->> 'summary',
    p_hero ->> 'playstyle',
    p_hero ->> 'imageUrl',
    p_hero,
    now()
  )
  on conflict (id) do update set
    name = excluded.name,
    role = excluded.role,
    difficulty = excluded.difficulty,
    summary = excluded.summary,
    playstyle = excluded.playstyle,
    image_url = excluded.image_url,
    raw_json = excluded.raw_json,
    updated_at = excluded.updated_at;

  delete from public.hero_list_items where hero_id = v_id;

  insert into public.hero_list_items (hero_id, item_type, value, sort_order)
  select v_id, lists.item_type, item.element, (item.ordinal - 1)::integer
  from (
    values
      ('strength', 'strengths'),
      ('weakness', 'weaknesses'),
      ('counter', 'counters'),
      ('synergy', 'synergies')
  ) as lists(item_type, json_key)
  cross join lateral jsonb_array_elements_text(
    case
      when jsonb_typeof(p_hero -> lists.json_key) = 'array' then p_hero -> lists.json_key
      else '[]'::jsonb
    end
  ) with ordinality as item(element, ordinal);

  delete from public.hero_abilities where hero_id = v_id;

  insert into public.hero_abilities (
    hero_id, kit_role, kit_label, name, ability_type, description, technical_details, sort_order
  )
  select
    v_id,
    kit.kit_role,
    kit.kit_label,
    ability.element ->> 'name',
    ability.element ->> 'type',
    ability.element ->> 'description',
    case
      when jsonb_typeof(ability.element -> 'technicalDetails') = 'array'
        then ability.element -> 'technicalDetails'
      else '[]'::jsonb
    end,
    (ability.ordinal - 1)::integer
  from (
    select null::text as kit_role, null::text as kit_label, p_hero -> 'abilities' as abilities
    union all
    select role_kit.element ->> 'role', role_kit.element ->> 'label', role_kit.element -> 'abilities'
    from jsonb_array_elements(
      case
        when jsonb_typeof(p_hero -> 'roleAbilityKits') = 'array' then p_hero -> 'roleAbilityKits'
        else '[]'::jsonb
      end
    ) as role_kit(element)
  ) as kit
  cross join lateral jsonb_array_elements(
    case
      when jsonb_typeof(kit.abilities) = 'array' then kit.abilities
      else '[]'::jsonb
    end
  ) with ordinality as ability(element, ordinal);
end;
$$;

revoke all on function public.save_hero(jsonb) from public, anon, authenticated;
grant execute on function public.save_hero(jsonb) to service_role;
