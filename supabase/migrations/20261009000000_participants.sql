-- Scoreboard lines of every player in a recorded match (issue 735, ADR-0011): no column for damage,
-- healing, accuracy, damage blocked or ult charge. Additive only; touches no existing table.

create table if not exists public.participants (
  id bigint generated by default as identity primary key,
  -- One value for the same match whoever recorded it; see `record_match_participants`.
  fingerprint text not null,
  half_season numeric(4,1) not null,
  played_at timestamptz not null,
  -- Either may be missing (masked names, no uid), but never both.
  uid text,
  name text,
  team smallint,
  hero_id integer,
  kills integer,
  deaths integer,
  assists integer,
  is_win boolean,
  -- A keyed hash of the recording user's verified Overwolf username, never the username itself.
  recorded_by text not null,
  recorded_at timestamptz not null default now(),
  constraint participants_has_identity check (uid is not null or name is not null)
);

create index if not exists participants_fingerprint_played_at_idx
  on public.participants (fingerprint, played_at);
create index if not exists participants_uid_idx
  on public.participants (uid) where uid is not null;
create index if not exists participants_name_idx
  on public.participants (lower(btrim(name))) where name is not null;
create index if not exists participants_played_at_idx
  on public.participants (played_at);

-- Nothing reads these rows yet. The per-uid read function (issue 736) is the only door that opens.
alter table public.participants enable row level security;
revoke all on public.participants from anon, authenticated;

-- A player who asked for deletion. `kind` is 'uid' or 'name'; a name is stored lower-cased and
-- trimmed, so the same player is matched however the game cased it.
create table if not exists public.do_not_store (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('uid', 'name')),
  key text not null check (key <> ''),
  added_at timestamptz not null default now(),
  unique (kind, key)
);

alter table public.do_not_store enable row level security;
revoke all on public.do_not_store from anon, authenticated;

-- When each half-season began, so retention can tell when a match's "next half-season" has ended.
-- Maintained by hand each half-season (docs/supabase-prod-checklist.md); a missing row only means
-- the six-month cap in `purge_expired_participants` is what removes the rows.
create table if not exists public.half_seasons (
  half_season numeric(4,1) primary key,
  starts_at timestamptz not null
);

alter table public.half_seasons enable row level security;
revoke all on public.half_seasons from anon, authenticated;

insert into public.half_seasons (half_season, starts_at) values
  (10.0, '2026-09-11T09:00:00Z'),
  (10.5, '2026-10-09T09:00:00Z')
on conflict (half_season) do nothing;

-- One row per accepted upload, so `claim_upload_slot` can cap how many one user sends per hour.
create table if not exists public.participant_upload_log (
  id bigint generated by default as identity primary key,
  recorded_by text not null,
  uploaded_at timestamptz not null default now()
);

create index if not exists participant_upload_log_recorder_idx
  on public.participant_upload_log (recorded_by, uploaded_at);

alter table public.participant_upload_log enable row level security;
revoke all on public.participant_upload_log from anon, authenticated;

-- Takes one of the caller's upload slots. Returns 0 when granted, otherwise the seconds until the
-- oldest upload in the window ages out. The advisory lock makes the count-then-insert exact for
-- one recorder.
create or replace function public.claim_upload_slot(
  p_recorded_by text,
  p_limit integer,
  p_window interval
) returns integer
language plpgsql
set search_path = ''
as $$
declare
  used integer;
  oldest timestamptz;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_recorded_by, 0));

  delete from public.participant_upload_log where uploaded_at < now() - p_window;

  select count(*), min(uploaded_at) into used, oldest
  from public.participant_upload_log
  where recorded_by = p_recorded_by;

  if used >= p_limit then
    return greatest(1, ceil(extract(epoch from (oldest + p_window - now())))::integer);
  end if;

  insert into public.participant_upload_log (recorded_by) values (p_recorded_by);
  return 0;
end
$$;

-- Stores one match's scoreboard lines and returns how many rows were written. A second upload of the
-- same fingerprint within 4 minutes is the same match and is dropped whole; do_not_store players are skipped.
create or replace function public.record_match_participants(
  p_fingerprint text,
  p_half_season numeric,
  p_played_at timestamptz,
  p_recorded_by text,
  p_players jsonb
) returns integer
language plpgsql
set search_path = ''
as $$
declare
  written integer;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_fingerprint, 0));

  if exists (
    select 1 from public.participants
    where fingerprint = p_fingerprint
      and played_at between p_played_at - interval '4 minutes' and p_played_at + interval '4 minutes'
  ) then
    return 0;
  end if;

  insert into public.participants
    (fingerprint, half_season, played_at, uid, name, team, hero_id, kills, deaths, assists, is_win, recorded_by)
  select
    p_fingerprint, p_half_season, p_played_at,
    x.uid, x.name, x.team, x.hero_id, x.kills, x.deaths, x.assists, x.is_win, p_recorded_by
  from jsonb_to_recordset(p_players) as x(
    uid text, name text, team smallint, hero_id integer,
    kills integer, deaths integer, assists integer, is_win boolean
  )
  where not exists (
    select 1 from public.do_not_store d
    where (d.kind = 'uid' and d.key = x.uid)
       or (d.kind = 'name' and d.key = lower(btrim(x.name)))
  );

  get diagnostics written = row_count;
  return written;
end
$$;

-- Deletes a player's rows and keeps every later upload from storing them again. Either argument
-- may be null; a name is matched case-insensitively. Returns the rows deleted.
create or replace function public.forget_player(
  p_uid text default null,
  p_name text default null
) returns integer
language plpgsql
set search_path = ''
as $$
declare
  name_key text := lower(btrim(p_name));
  removed integer;
begin
  if nullif(btrim(p_uid), '') is not null then
    insert into public.do_not_store (kind, key) values ('uid', btrim(p_uid))
    on conflict (kind, key) do nothing;
  end if;
  if nullif(name_key, '') is not null then
    insert into public.do_not_store (kind, key) values ('name', name_key)
    on conflict (kind, key) do nothing;
  end if;

  delete from public.participants
  where (nullif(btrim(p_uid), '') is not null and uid = btrim(p_uid))
     or (nullif(name_key, '') is not null and lower(btrim(name)) = name_key);
  get diagnostics removed = row_count;
  return removed;
end
$$;

-- Retention (privacy policy section 7): a row goes when the half-season after its own has ended,
-- and in any case six months after the match. Returns the rows deleted.
create or replace function public.purge_expired_participants() returns integer
language plpgsql
set search_path = ''
as $$
declare
  removed integer;
begin
  delete from public.participants p
  where p.played_at < now() - interval '6 months'
     or exists (
       select 1 from public.half_seasons h
       where h.half_season = p.half_season + 1 and h.starts_at <= now()
     );
  get diagnostics removed = row_count;
  return removed;
end
$$;

-- Functions are executable by everyone by default. These are for the edge function's service role
-- only; without this, anyone holding the publishable key could call them over the REST endpoint.
revoke execute on function public.claim_upload_slot(text, integer, interval) from public, anon, authenticated;
revoke execute on function public.record_match_participants(text, numeric, timestamptz, text, jsonb) from public, anon, authenticated;
revoke execute on function public.forget_player(text, text) from public, anon, authenticated;
revoke execute on function public.purge_expired_participants() from public, anon, authenticated;
grant execute on function public.claim_upload_slot(text, integer, interval) to service_role;
grant execute on function public.record_match_participants(text, numeric, timestamptz, text, jsonb) to service_role;
grant execute on function public.forget_player(text, text) to service_role;
grant execute on function public.purge_expired_participants() to service_role;

-- Run the purge daily where pg_cron is available. The edge function also runs it after each
-- upload, so retention does not depend on the scheduler being enabled.
do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
    perform cron.unschedule(jobid) from cron.job where jobname = 'purge-expired-participants';
    perform cron.schedule('purge-expired-participants', '17 3 * * *', 'select public.purge_expired_participants()');
  else
    raise warning 'pg_cron is not available: participant retention runs only from the edge function';
  end if;
exception when others then
  raise warning 'pg_cron job not scheduled (%): participant retention runs only from the edge function', sqlerrm;
end
$$;
