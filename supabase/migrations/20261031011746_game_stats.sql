-- Game stats for the website, moved from Turso (issue 109). Additive only: two new tables and the
-- function that writes them. The hourly sync records its runs in `sync_runs`, created by
-- 20261030042403_hero_content.sql.
--
-- Nothing here is readable with the publishable key: RLS is on, there is no policy, and only the
-- service role has grants. The website reads and writes through its server.

-- One capture per UTC hour. `capture_bucket` is the hour; being unique, it stops page traffic and
-- cron retries from storing a second capture of the same hour.
create table if not exists public.game_stat_snapshots (
  id bigint generated by default as identity primary key,
  capture_bucket timestamptz not null,
  snapshot_date text not null,
  captured_at timestamptz not null,
  current_player_source text not null,
  current_player_source_url text not null,
  created_at timestamptz not null default now(),
  constraint game_stat_snapshots_capture_bucket_key unique (capture_bucket)
);

-- Each game's values in a capture.
create table if not exists public.game_stat_snapshot_games (
  id bigint generated by default as identity primary key,
  snapshot_id bigint not null references public.game_stat_snapshots (id) on delete cascade,
  app_id integer not null,
  name text not null,
  category text not null,
  current_players integer not null,
  daily_peak integer not null,
  all_time_peak integer not null,
  steam_daily_rank text not null,
  top_seller_rank text not null,
  twitch_viewers integer not null,
  review_summary text not null,
  source_url text not null,
  constraint game_stat_snapshot_games_snapshot_app_key unique (snapshot_id, app_id)
);

create index if not exists game_stat_snapshots_captured_at_idx
  on public.game_stat_snapshots (captured_at desc);
create index if not exists game_stat_snapshot_games_app_idx
  on public.game_stat_snapshot_games (app_id, snapshot_id);

alter table public.game_stat_snapshots enable row level security;
alter table public.game_stat_snapshot_games enable row level security;

revoke all on table public.game_stat_snapshots from anon, authenticated;
revoke all on table public.game_stat_snapshot_games from anon, authenticated;

grant select, insert, update, delete on table public.game_stat_snapshots to service_role;
grant select, insert, update, delete on table public.game_stat_snapshot_games to service_role;

revoke all on sequence public.game_stat_snapshots_id_seq from anon, authenticated;
revoke all on sequence public.game_stat_snapshot_games_id_seq from anon, authenticated;
grant usage, select on sequence public.game_stat_snapshots_id_seq to service_role;
grant usage, select on sequence public.game_stat_snapshot_games_id_seq to service_role;

-- Stores the capture of `p_capture_bucket` unless that hour already has one, then returns the
-- hour's stored capture and the capture before it, with that capture's games. One transaction, so a
-- capture is never left without its games. The first capture of an hour wins: a later one in the
-- same hour stores nothing.
--
-- `p_games` is a list of `{ appId, name, category, currentPlayers, dailyPeak, allTimePeak,
-- steamDailyRank, topSellerRank, twitchViewers, reviewSummary, sourceUrl }`.
create or replace function public.record_game_stat_snapshot(
  p_capture_bucket timestamptz,
  p_snapshot_date text,
  p_captured_at timestamptz,
  p_current_player_source text,
  p_current_player_source_url text,
  p_games jsonb
)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_current public.game_stat_snapshots%rowtype;
  v_previous public.game_stat_snapshots%rowtype;
begin
  if jsonb_typeof(p_games) is distinct from 'array' then
    raise exception 'record_game_stat_snapshot: p_games is not a list';
  end if;

  insert into public.game_stat_snapshots (
    capture_bucket, snapshot_date, captured_at, current_player_source, current_player_source_url
  )
  values (
    p_capture_bucket, p_snapshot_date, p_captured_at, p_current_player_source, p_current_player_source_url
  )
  on conflict (capture_bucket) do nothing;

  select * into strict v_current
  from public.game_stat_snapshots
  where capture_bucket = p_capture_bucket;

  insert into public.game_stat_snapshot_games (
    snapshot_id, app_id, name, category, current_players, daily_peak, all_time_peak,
    steam_daily_rank, top_seller_rank, twitch_viewers, review_summary, source_url
  )
  select
    v_current.id,
    (game ->> 'appId')::integer,
    game ->> 'name',
    game ->> 'category',
    (game ->> 'currentPlayers')::integer,
    (game ->> 'dailyPeak')::integer,
    (game ->> 'allTimePeak')::integer,
    game ->> 'steamDailyRank',
    game ->> 'topSellerRank',
    (game ->> 'twitchViewers')::integer,
    game ->> 'reviewSummary',
    game ->> 'sourceUrl'
  from jsonb_array_elements(p_games) as games(game)
  on conflict (snapshot_id, app_id) do nothing;

  select * into v_previous
  from public.game_stat_snapshots
  where capture_bucket < p_capture_bucket
  order by capture_bucket desc
  limit 1;

  return jsonb_build_object(
    'current', jsonb_build_object(
      'id', v_current.id,
      'snapshotDate', v_current.snapshot_date,
      'capturedAt', v_current.captured_at
    ),
    'previous', case when v_previous.id is null then null else jsonb_build_object(
      'id', v_previous.id,
      'snapshotDate', v_previous.snapshot_date,
      'capturedAt', v_previous.captured_at,
      'games', (
        select coalesce(jsonb_agg(jsonb_build_object(
          'appId', g.app_id,
          'name', g.name,
          'category', g.category,
          'currentPlayers', g.current_players,
          'dailyPeak', g.daily_peak,
          'allTimePeak', g.all_time_peak,
          'steamDailyRank', g.steam_daily_rank,
          'topSellerRank', g.top_seller_rank,
          'twitchViewers', g.twitch_viewers,
          'reviewSummary', g.review_summary,
          'sourceUrl', g.source_url
        ) order by g.app_id), '[]'::jsonb)
        from public.game_stat_snapshot_games g
        where g.snapshot_id = v_previous.id
      )
    ) end
  );
end;
$$;

revoke all on function public.record_game_stat_snapshot(timestamptz, text, timestamptz, text, text, jsonb)
  from public, anon, authenticated;
grant execute on function public.record_game_stat_snapshot(timestamptz, text, timestamptz, text, text, jsonb)
  to service_role;
