-- Issue 176: store what a newer overlay adds to an upload, beside the scoreboard and without touching
-- it: the recorder's own damage, healing, damage blocked and seconds per hero, and the match's kill
-- feed (which hero killed which, how often). Shipped overlays send neither and nothing changes for
-- them.
--
-- Additive. No existing table gains a column and `record_match_participants` keeps its exact
-- signature: the new data goes through a new function with a new name, which the Edge Function
-- calls after it, only when the upload carried the new fields. A second overload of the old function
-- would make every upload fail with PGRST203.

-- One row per hero the recorder played in a match. It belongs to the recorder's own `participants`
-- line, so retention and `forget_player` reach it through the foreign key: delete the line and the
-- figures go with it. Each figure is null when the app did not have it (never 0 in its place).
create table if not exists public.participant_hero_figures (
  participant_id bigint not null references public.participants (id) on delete cascade,
  hero_id integer not null check (hero_id > 0),
  seconds integer check (seconds between 0 and 7200),
  damage_dealt integer check (damage_dealt between 0 and 1000000),
  healing integer check (healing between 0 and 1000000),
  damage_blocked integer check (damage_blocked between 0 and 1000000),
  recorded_at timestamptz not null default now(),
  primary key (participant_id, hero_id),
  constraint participant_hero_figures_has_a_figure check (
    seconds is not null or damage_dealt is not null or healing is not null or damage_blocked is not null
  )
);

-- A match's kill feed, one row per (killer hero, victim hero) pair, stored once per match whoever
-- uploaded it. Heroes only: no player is named, so a row can be read without identifying anyone.
-- A match is its roster fingerprint plus its start time, as `participants` and the hero aggregates
-- read it; half_season and played_at are copied from that match's scoreboard rows.
create table if not exists public.match_hero_kills (
  id bigint generated by default as identity primary key,
  fingerprint text not null,
  half_season numeric(4,1) not null,
  played_at timestamptz not null,
  killer_hero text not null check (killer_hero ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(killer_hero) <= 40),
  victim_hero text not null check (victim_hero ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(victim_hero) <= 40),
  kills integer not null check (kills between 1 and 999),
  recorded_at timestamptz not null default now(),
  unique (fingerprint, played_at, killer_hero, victim_hero)
);

create index if not exists match_hero_kills_half_season_idx on public.match_hero_kills (half_season);

-- Same posture as `participants`: RLS on, no policy, nothing for the publishable key.
alter table public.participant_hero_figures enable row level security;
alter table public.match_hero_kills enable row level security;
revoke all on public.participant_hero_figures from anon, authenticated;
revoke all on public.match_hero_kills from anon, authenticated;
grant select, insert, update, delete on public.participant_hero_figures to service_role;
grant select, insert, update, delete on public.match_hero_kills to service_role;
revoke all on sequence public.match_hero_kills_id_seq from anon, authenticated;
grant usage, select on sequence public.match_hero_kills_id_seq to service_role;

-- Stores one match's extra figures and returns how many rows each kind wrote, as
-- {"hero_figures": n, "hero_kills": n}. The match must already be in `participants` (the caller
-- records the scoreboard first), so a kill feed can never be stored for a match nobody recorded.
--
-- Safe to repeat: a hero's figures for a recorder are written once, and a kill feed is written once
-- per match (the first uploader's wins), so two uploaders of one match store it once. The recorder's
-- own figures are the one thing a second uploader still adds.
create or replace function public.record_match_extras(
  p_fingerprint text,
  p_played_at timestamptz,
  p_recorder_uid text,
  p_hero_figures jsonb default '[]'::jsonb,
  p_hero_kills jsonb default '[]'::jsonb
) returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  match_half_season numeric;
  match_played_at timestamptz;
  recorder_line bigint;
  figures_written integer := 0;
  kills_written integer := 0;
begin
  -- A different lock seed from `record_match_participants`, so the two never wait on each other.
  perform pg_advisory_xact_lock(hashtextextended(p_fingerprint, 1));

  -- The same 4 minute window `record_match_participants` uses to call two uploads one match.
  select p.half_season, p.played_at into match_half_season, match_played_at
  from public.participants p
  where p.fingerprint = p_fingerprint
    and p.played_at between p_played_at - interval '4 minutes' and p_played_at + interval '4 minutes'
  order by abs(extract(epoch from p.played_at - p_played_at)), p.id
  limit 1;

  if not found then
    return jsonb_build_object('hero_figures', 0, 'hero_kills', 0);
  end if;

  if p_recorder_uid is not null and jsonb_typeof(p_hero_figures) = 'array' then
    select p.id into recorder_line
    from public.participants p
    where p.fingerprint = p_fingerprint and p.played_at = match_played_at and p.uid = p_recorder_uid
    limit 1;

    if found then
      -- The table's limits are applied here too, so a value outside them is left out (a missing
      -- figure) instead of failing the whole call.
      insert into public.participant_hero_figures
        (participant_id, hero_id, seconds, damage_dealt, healing, damage_blocked)
      select recorder_line, f.hero_id, f.seconds, f.damage_dealt, f.healing, f.damage_blocked
      from (
        select x.hero_id,
               case when x.seconds between 0 and 7200 then x.seconds end as seconds,
               case when x.damage_dealt between 0 and 1000000 then x.damage_dealt end as damage_dealt,
               case when x.healing between 0 and 1000000 then x.healing end as healing,
               case when x.damage_blocked between 0 and 1000000 then x.damage_blocked end as damage_blocked
        from jsonb_to_recordset(p_hero_figures) as x(
          hero_id integer, seconds integer, damage_dealt integer, healing integer, damage_blocked integer
        )
        where x.hero_id > 0
      ) f
      where f.seconds is not null or f.damage_dealt is not null or f.healing is not null or f.damage_blocked is not null
      on conflict (participant_id, hero_id) do nothing;
      get diagnostics figures_written = row_count;
    end if;
  end if;

  if jsonb_typeof(p_hero_kills) = 'array' and not exists (
    select 1 from public.match_hero_kills k
    where k.fingerprint = p_fingerprint and k.played_at = match_played_at
  ) then
    insert into public.match_hero_kills (fingerprint, half_season, played_at, killer_hero, victim_hero, kills)
    select p_fingerprint, match_half_season, match_played_at, x.killer, x.victim, x.kills
    from jsonb_to_recordset(p_hero_kills) as x(killer text, victim text, kills integer)
    where x.kills between 1 and 999
      and x.killer ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(x.killer) <= 40
      and x.victim ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(x.victim) <= 40
    on conflict (fingerprint, played_at, killer_hero, victim_hero) do nothing;
    get diagnostics kills_written = row_count;
  end if;

  return jsonb_build_object('hero_figures', figures_written, 'hero_kills', kills_written);
end
$$;

-- Postgres grants EXECUTE to everyone on a new function; this one is for the Edge Function's service role.
revoke execute on function public.record_match_extras(text, timestamptz, text, jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.record_match_extras(text, timestamptz, text, jsonb, jsonb) to service_role;
