-- Links a website account to an in-game player with a one-time code (issue 264, ADR-0004). Additive
-- only: it touches no object the overlay calls.
--
-- The link rests on the verified Overwolf session: `recorder_id` is the same keyed hash that
-- `track-match-history` stores as `recorded_by`. The uid, name and avatar that come with it are the
-- app's claims and are only ever shown, never used to decide who owns what.
--
-- Flow: the app calls the `issue-link-code` Edge Function, which calls `issue_link_code` (service
-- role). The player types the code on the website, which calls `redeem_link_code` with the
-- account's own token. Writes to `player_links` happen only inside these functions.

-- The link itself. `recorder_id` is unique and `player_uid` is not: a uid is a claim, so letting it
-- be unique would let anyone squat another player's. A fresh code redeemed by another account
-- moves the link there ("latest proof wins").
create table if not exists public.player_links (
  user_id uuid primary key references auth.users (id) on delete cascade,
  recorder_id text not null unique,
  player_uid text not null,
  player_name text not null,
  avatar_url text check (avatar_url is null or avatar_url like 'https://%'),
  linked_at timestamptz not null default now()
);

alter table public.player_links enable row level security;

-- An account reads its own link and nothing else. Linking and unlinking go through the functions below.
revoke all on public.player_links from anon, authenticated;
grant select on public.player_links to authenticated;

drop policy if exists "Links are readable by their owner" on public.player_links;
create policy "Links are readable by their owner"
  on public.player_links for select to authenticated
  using ((select auth.uid()) = user_id);

-- The code waiting to be typed. One per recorder, so issuing a new one cancels the old. Only the
-- hash of the code is kept. Nothing here is readable by a client: with RLS on and no policy, only
-- the service role and the functions below reach it.
create table if not exists public.link_codes (
  recorder_id text primary key,
  code_hash text not null unique,
  player_uid text not null,
  player_name text not null,
  avatar_url text check (avatar_url is null or avatar_url like 'https://%'),
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.link_codes enable row level security;
revoke all on public.link_codes from anon, authenticated;

-- One row per code issued (subject is the recorder) and per wrong code typed (subject is the
-- account), so both can be capped. Not readable by a client. A wrong code also carries the account
-- id in `user_id`, so deleting the account deletes its rows.
create table if not exists public.link_attempt_log (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('issue', 'redeem_failed')),
  subject text not null,
  user_id uuid references auth.users (id) on delete cascade,
  attempted_at timestamptz not null default now(),
  check ((kind = 'redeem_failed') = (user_id is not null))
);

create index if not exists link_attempt_log_subject_idx
  on public.link_attempt_log (kind, subject, attempted_at);

alter table public.link_attempt_log enable row level security;
revoke all on public.link_attempt_log from anon, authenticated;

-- The stored form of a code: SHA-256 of its eight canonical characters, in hex. The website
-- canonicalises what the player typed before it gets here.
create or replace function public.link_code_hash(p_code text)
returns text
language sql
immutable
set search_path = ''
as $$
  select encode(sha256(convert_to(coalesce(p_code, ''), 'UTF8')), 'hex')
$$;

-- Stores a new code for a recorder, cancelling their old one. Returns
-- {"status":"issued","expiresAt":...}, or {"status":"rate_limited","retryAfter":seconds} once the
-- recorder has had p_limit codes inside p_window. The advisory lock makes count-then-insert exact.
create or replace function public.issue_link_code(
  p_recorder_id text,
  p_code text,
  p_player_uid text,
  p_player_name text,
  p_avatar_url text,
  p_ttl interval,
  p_limit integer,
  p_window interval
) returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  used integer;
  oldest timestamptz;
  expires timestamptz;
begin
  perform pg_advisory_xact_lock(hashtextextended('issue:' || p_recorder_id, 0));

  delete from public.link_attempt_log where kind = 'issue' and attempted_at < now() - p_window;
  delete from public.link_codes where expires_at < now();

  select count(*), min(attempted_at) into used, oldest
  from public.link_attempt_log
  where kind = 'issue' and subject = p_recorder_id and attempted_at > now() - p_window;

  if used >= p_limit then
    return jsonb_build_object(
      'status', 'rate_limited',
      'retryAfter', greatest(1, ceil(extract(epoch from (oldest + p_window - now())))::integer)
    );
  end if;

  expires := now() + p_ttl;

  insert into public.link_attempt_log (kind, subject) values ('issue', p_recorder_id);

  insert into public.link_codes (recorder_id, code_hash, player_uid, player_name, avatar_url, expires_at)
  values (p_recorder_id, public.link_code_hash(p_code), p_player_uid, p_player_name, p_avatar_url, expires)
  on conflict (recorder_id) do update
    set code_hash = excluded.code_hash,
        player_uid = excluded.player_uid,
        player_name = excluded.player_name,
        avatar_url = excluded.avatar_url,
        expires_at = excluded.expires_at,
        created_at = now();

  return jsonb_build_object('status', 'issued', 'expiresAt', expires);
end
$$;

-- Redeems a code for the signed-in account. Returns {"status":"linked","name":...,"avatarUrl":...},
-- {"status":"invalid"} (wrong, used and expired codes are not told apart) or
-- {"status":"rate_limited","retryAfter":seconds}. A refusal returns rather than raises, so the
-- failure it logs is kept. Five wrong codes in 15 minutes lock the account out for the rest of the
-- window, even for a right code.
create or replace function public.redeem_link_code(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  account uuid := (select auth.uid());
  found_code public.link_codes%rowtype;
  failures integer;
  oldest timestamptz;
begin
  if account is null then
    raise exception 'Sign in to link a player' using errcode = '28000';
  end if;

  -- An anonymous Supabase session has an account id but no identity worth linking.
  if coalesce((select auth.jwt()) ->> 'is_anonymous', 'false') = 'true' then
    raise exception 'Create an account to link a player' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('redeem:' || account::text, 0));

  delete from public.link_attempt_log where kind = 'redeem_failed' and attempted_at < now() - interval '15 minutes';

  select count(*), min(attempted_at) into failures, oldest
  from public.link_attempt_log
  where kind = 'redeem_failed' and subject = account::text and attempted_at > now() - interval '15 minutes';

  if failures >= 5 then
    return jsonb_build_object(
      'status', 'rate_limited',
      'retryAfter', greatest(1, ceil(extract(epoch from (oldest + interval '15 minutes' - now())))::integer)
    );
  end if;

  -- Deleting is what makes a code single use, even for two accounts typing it at once.
  delete from public.link_codes
  where code_hash = public.link_code_hash(p_code) and expires_at > now()
  returning * into found_code;

  if not found then
    insert into public.link_attempt_log (kind, subject, user_id) values ('redeem_failed', account::text, account);
    return jsonb_build_object('status', 'invalid');
  end if;

  perform pg_advisory_xact_lock(hashtextextended('recorder:' || found_code.recorder_id, 0));

  -- Latest proof wins: the recorder leaves any other account, and this account leaves any other player.
  delete from public.player_links where recorder_id = found_code.recorder_id or user_id = account;

  insert into public.player_links (user_id, recorder_id, player_uid, player_name, avatar_url)
  values (account, found_code.recorder_id, found_code.player_uid, found_code.player_name, found_code.avatar_url);

  return jsonb_build_object('status', 'linked', 'name', found_code.player_name, 'avatarUrl', found_code.avatar_url);
end
$$;

-- Removes the signed-in account's link. Nothing else is left behind: the code was deleted when it was used.
create or replace function public.unlink_player()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  account uuid := (select auth.uid());
begin
  if account is null then
    raise exception 'Sign in to unlink a player' using errcode = '28000';
  end if;

  delete from public.player_links where user_id = account;
end
$$;

-- Deletes what has outlived its use: attempt rows past their window (an hour for codes issued, 15
-- minutes for wrong codes) and codes that expired unused, which hold a player's name, uid and avatar.
-- Run by the schedule below; the issuing and redeeming functions also sweep their own kind, so
-- retention does not depend on the scheduler being enabled.
create or replace function public.purge_link_data()
returns void
language plpgsql
set search_path = ''
as $$
begin
  delete from public.link_attempt_log
  where (kind = 'issue' and attempted_at < now() - interval '1 hour')
     or (kind = 'redeem_failed' and attempted_at < now() - interval '15 minutes');

  delete from public.link_codes where expires_at < now();
end
$$;

-- Postgres grants EXECUTE to everyone on a new function; restate who may call each.
revoke execute on function public.link_code_hash(text) from public, anon, authenticated;
revoke execute on function public.issue_link_code(text, text, text, text, text, interval, integer, interval) from public, anon, authenticated;
revoke execute on function public.redeem_link_code(text) from public, anon, authenticated;
revoke execute on function public.unlink_player() from public, anon, authenticated;
revoke execute on function public.purge_link_data() from public, anon, authenticated;
grant execute on function public.link_code_hash(text) to service_role;
grant execute on function public.issue_link_code(text, text, text, text, text, interval, integer, interval) to service_role;
grant execute on function public.redeem_link_code(text) to authenticated;
grant execute on function public.unlink_player() to authenticated;
grant execute on function public.purge_link_data() to service_role;

-- Run the purge every five minutes where pg_cron is available (same pattern as the participants purge).
do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
    perform cron.unschedule(jobid) from cron.job where jobname = 'purge-link-data';
    perform cron.schedule('purge-link-data', '*/5 * * * *', 'select public.purge_link_data()');
  else
    raise warning 'pg_cron is not available: link data is swept only when codes are issued or redeemed';
  end if;
exception when others then
  raise warning 'pg_cron job not scheduled (%): link data is swept only when codes are issued or redeemed', sqlerrm;
end
$$;
