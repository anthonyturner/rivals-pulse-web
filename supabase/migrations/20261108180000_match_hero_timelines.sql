-- Issue 654: store each player's hero timeline for a match, so the website can later work out which
-- hero changes happened while which enemy heroes were on the field. A newer overlay sends it as
-- `hero_timelines` (team and ordered picks, no uid and no name); shipped overlays send nothing and
-- nothing changes for them.
--
-- Additive. No existing table gains a column and `record_match_participants` and
-- `record_match_extras` keep their exact signatures: the timelines go through a new function with a
-- new name, which the Edge Function calls after them, only when the upload carried the field.

-- One row per pick. A match is its roster fingerprint plus its start time, as `match_hero_kills`
-- reads it; half_season and played_at are copied from that match's scoreboard rows. `timeline_no`
-- only groups the picks of one player (the order they came in), and no uid or name is kept.
-- Retention deletes these rows on the schedule of `match_hero_kills`: through a fingerprint, a team
-- and the final hero a timeline could be linked back to a roster line, as a kill row can.
create table if not exists public.match_hero_timelines (
  id bigint generated by default as identity primary key,
  fingerprint text not null,
  half_season numeric(4,1) not null,
  played_at timestamptz not null,
  team smallint not null check (team between 0 and 9),
  timeline_no smallint not null check (timeline_no between 1 and 12),
  pick_no smallint not null check (pick_no between 1 and 20),
  hero_id integer not null check (hero_id > 0),
  at_second integer not null check (at_second between 0 and 7200),
  recorded_at timestamptz not null default now(),
  unique (fingerprint, played_at, timeline_no, pick_no)
);

create index if not exists match_hero_timelines_half_season_idx on public.match_hero_timelines (half_season);

-- Same posture as `participants`: RLS on, no policy, nothing for the publishable key.
alter table public.match_hero_timelines enable row level security;
revoke all on public.match_hero_timelines from anon, authenticated;
grant select, insert, update, delete on public.match_hero_timelines to service_role;
revoke all on sequence public.match_hero_timelines_id_seq from anon, authenticated;
grant usage, select on sequence public.match_hero_timelines_id_seq to service_role;

-- The whole number inside a JSON value, or null when it is absent, not a number, a fraction or out of
-- range. The nested `case` is what keeps text that is not a number from ever reaching the cast:
-- Postgres does not promise to stop at the first false condition of an `and`, but it does for a `case`.
create or replace function public.json_whole_number(p_value jsonb, p_min integer, p_max integer) returns integer
language sql
immutable
set search_path = ''
as $$
  select case
    when jsonb_typeof(p_value) = 'number' then
      case
        when (p_value #>> '{}')::numeric between p_min and p_max
          and (p_value #>> '{}')::numeric = trunc((p_value #>> '{}')::numeric)
        then (p_value #>> '{}')::numeric::integer
      end
  end
$$;

-- Stores one match's hero timelines and returns how many player timelines it wrote. The match must
-- already be in `participants`, so timelines can never be stored for a match nobody recorded.
--
-- Safe to repeat: timelines are written once per match (the first uploader's wins), so two uploaders
-- of one match store them once. A timeline is stored whole or not at all: it needs a team from 0 to 9,
-- 1 to 20 picks, each with a hero id and a second from 0 to 7200, and seconds that never go back. A
-- list of more than 12 players is not a real one and none of it is stored.
create or replace function public.record_match_hero_timelines(
  p_fingerprint text,
  p_played_at timestamptz,
  p_hero_timelines jsonb
) returns integer
language plpgsql
set search_path = ''
as $$
declare
  match_half_season numeric;
  match_played_at timestamptz;
  written integer := 0;
begin
  if jsonb_typeof(p_hero_timelines) is distinct from 'array' or jsonb_array_length(p_hero_timelines) not between 1 and 12 then
    return 0;
  end if;

  -- A different lock seed from the three other match writers (seeds 0, 1 and 2), so none of them waits on another.
  perform pg_advisory_xact_lock(hashtextextended(p_fingerprint, 3));

  -- The same 4 minute window `record_match_participants` uses to call two uploads one match.
  select p.half_season, p.played_at into match_half_season, match_played_at
  from public.participants p
  where p.fingerprint = p_fingerprint
    and p.played_at between p_played_at - interval '4 minutes' and p_played_at + interval '4 minutes'
  order by abs(extract(epoch from p.played_at - p_played_at)), p.id
  limit 1;

  if not found then
    return 0;
  end if;

  if exists (
    select 1 from public.match_hero_timelines t
    where t.fingerprint = p_fingerprint and t.played_at = match_played_at
  ) then
    return 0;
  end if;

  with picks as (
    select t.ord as timeline_no,
           public.json_whole_number(t.timeline -> 'team', 0, 9) as team,
           p.ord as pick_no,
           public.json_whole_number(p.pick -> 'hero_id', 1, 2147483647) as hero_id,
           public.json_whole_number(p.pick -> 'at_second', 0, 7200) as at_second
    from jsonb_array_elements(p_hero_timelines) with ordinality as t(timeline, ord)
    cross join lateral jsonb_array_elements(
      case when jsonb_typeof(t.timeline -> 'picks') = 'array' then t.timeline -> 'picks' else '[]'::jsonb end
    ) with ordinality as p(pick, ord)
  ),
  ordered as (
    select k.timeline_no, k.team, k.pick_no, k.hero_id, k.at_second,
           k.at_second >= coalesce(lag(k.at_second) over (partition by k.timeline_no order by k.pick_no), 0) as in_order
    from picks k
  ),
  whole as (
    select o.timeline_no
    from ordered o
    group by o.timeline_no
    having count(*) between 1 and 20
      and bool_and(o.team is not null and o.hero_id is not null and o.at_second is not null and o.in_order)
  ),
  inserted as (
    insert into public.match_hero_timelines
      (fingerprint, half_season, played_at, team, timeline_no, pick_no, hero_id, at_second)
    select p_fingerprint, match_half_season, match_played_at, o.team, o.timeline_no, o.pick_no, o.hero_id, o.at_second
    from ordered o
    join whole w on w.timeline_no = o.timeline_no
    on conflict (fingerprint, played_at, timeline_no, pick_no) do nothing
    returning timeline_no
  )
  select count(distinct i.timeline_no) into written from inserted i;

  return written;
end
$$;

-- Postgres grants EXECUTE to everyone on a new function; these are for the Edge Function's service role.
revoke execute on function public.json_whole_number(jsonb, integer, integer) from public, anon, authenticated;
revoke execute on function public.record_match_hero_timelines(text, timestamptz, jsonb) from public, anon, authenticated;
grant execute on function public.json_whole_number(jsonb, integer, integer) to service_role;
grant execute on function public.record_match_hero_timelines(text, timestamptz, jsonb) to service_role;

-- Freezes every aggregate family before deleting; a later restatement must keep calling every freeze.
-- Restated from `20261107120000_triple_support_trios.sql` with one more delete: the timelines go on
-- the schedule of the kill feed. Returns the scoreboard rows deleted.
create or replace function public.purge_expired_participants() returns integer
language plpgsql
set search_path = ''
as $$
declare
  removed integer;
begin
  perform public.rebuild_hero_aggregates(due.half_season, true)
  from (
    select p.half_season from public.participants p
    group by p.half_season
    having public.participants_past_retention(p.half_season, min(p.played_at))
  ) due;

  perform public.freeze_extended_aggregates();
  perform public.freeze_hero_pair_aggregates();
  perform public.freeze_triple_support_aggregates();

  delete from public.participants p
  where public.participants_past_retention(p.half_season, p.played_at);
  get diagnostics removed = row_count;

  delete from public.match_hero_kills k
  where public.participants_past_retention(k.half_season, k.played_at);

  delete from public.match_hero_timelines t
  where public.participants_past_retention(t.half_season, t.played_at);

  return removed;
end
$$;

revoke execute on function public.purge_expired_participants() from public, anon, authenticated;
grant execute on function public.purge_expired_participants() to service_role;
