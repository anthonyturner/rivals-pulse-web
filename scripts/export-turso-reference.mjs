// One-off bridge from Turso to Supabase for the reference content (issue 106). It writes the SQL
// that `npx supabase db push` applies, so the copy needs no Supabase service key. Issue 110 deletes
// this file together with the rest of Turso.
//
//   node scripts/export-turso-reference.mjs --out supabase/migrations/<version>_reference_content_data.sql
//   node scripts/export-turso-reference.mjs --check supabase/migrations/<version>_reference_content_data.sql
//
// `--check` exits 1 when Turso has changed since the file was written; run it just before the push.
// The hero videos are not copied: Supabase's `hero_videos` already holds the same rows, which
// `verify-reference-content.mjs` proves.
import { createTursoClient } from './turso-client.mjs';
import {
  insertStatements,
  json,
  selectRows,
  text,
  utcTimestamp,
  writeOrCheckDataMigration,
} from './turso-data-migration.mjs';

// The sources this slice copies. The hero slice (issue 105) copied the hero syncs' snapshots and
// the home slice (issue 107) the home news sync's.
const SOURCE_KEYS = [
  'fandom-battlepasses',
  'fandom-deadpool',
  'fandom-deadpool-abilities-template',
  'steam-marvel-rivals-news',
];

await writeOrCheckDataMigration(buildSql);

async function buildSql() {
  const db = createTursoClient();

  try {
    const terms = await selectRows(db, 'SELECT * FROM glossary_terms ORDER BY id');
    const sources = await selectRows(
      db,
      `SELECT * FROM external_sources WHERE source_key IN (${SOURCE_KEYS.map(() => '?').join(', ')}) ORDER BY source_key`,
      SOURCE_KEYS,
    );

    return [
      '-- Reference content copied from Turso (issue 106). Generated by scripts/export-turso-reference.mjs; do not edit.',
      `-- ${terms.length} glossary terms, ${sources.length} sources.`,
      '--',
      '-- Safe to run twice: a row that already exists is left alone, so a re-run can never',
      '-- overwrite what the syncs have written since.',
      '',
      ...insertStatements('public.glossary_terms', [
        ['id', (row) => text(row.id)],
        ['term', (row) => text(row.term)],
        ['category', (row) => text(row.category)],
        ['definition', (row) => text(row.definition)],
        ['coach_note', (row) => text(row.coach_note)],
        ['example', (row) => text(row.example)],
        ['related_terms', (row) => json(row.related_terms_json)],
        ['source_name', (row) => text(row.source_name)],
        ['source_url', (row) => text(row.source_url)],
        ['raw_json', (row) => json(row.raw_json)],
        ['updated_at', (row) => utcTimestamp(row.updated_at)],
      ], terms),
      ...insertStatements('public.external_sources', [
        ['source_key', (row) => text(row.source_key)],
        ['source_name', (row) => text(row.source_name)],
        ['url', (row) => text(row.url)],
        ['payload', (row) => json(row.payload_json)],
        ['fetched_at', (row) => utcTimestamp(row.fetched_at)],
        ['status', (row) => text(row.status)],
        ['error', (row) => text(row.error)],
      ], sources),
    ].join('\n');
  } finally {
    db.close();
  }
}
