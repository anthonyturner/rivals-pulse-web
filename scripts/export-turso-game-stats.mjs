// One-off bridge from Turso to Supabase for the game stats (issue 109). It writes SQL, so the copy
// needs no Supabase service key. Issue 110 deletes this file together with the rest of Turso.
//
//   node scripts/export-turso-game-stats.mjs --out supabase/migrations/<version>_game_stats_data.sql
//     The data migration: every capture up to the latest hour Turso has, with Turso's ids.
//
//   node scripts/export-turso-game-stats.mjs --check supabase/migrations/<version>_game_stats_data.sql
//     Exits 1 unless Turso still holds exactly the rows the file copies. Turso gains a capture
//     every hour until the merge; those later hours do not fail the check, they are counted.
//
//   node scripts/export-turso-game-stats.mjs --top-up <data migration> --out tmp-game-stats-top-up.sql
//     After the merge: the SQL that copies every capture Turso took after the data migration's last
//     hour (`tmp-*` is gitignored). Apply it with `npx supabase db query --linked -f <that file>`.
//     Supabase gives those rows new ids, because by then it numbers its own captures. Safe to apply
//     twice: an hour Supabase already has, including one both databases captured during the
//     cutover, is left alone.
import { readFileSync, writeFileSync } from 'node:fs';

import { createTursoClient } from './turso-client.mjs';
import {
  insertStatements,
  integer,
  selectRows,
  text,
  utcTimestamp,
  writeOrCheckDataMigration,
} from './turso-data-migration.mjs';

const ROWS_PER_STATEMENT = 25;
const LAST_HOUR_LINE = /^-- Last hour copied: (\S+)$/m;

const SNAPSHOT_COLUMNS = [
  ['capture_bucket', (row) => utcTimestamp(row.capture_bucket)],
  ['snapshot_date', (row) => text(row.snapshot_date)],
  ['captured_at', (row) => utcTimestamp(row.captured_at)],
  ['current_player_source', (row) => text(row.current_player_source)],
  ['current_player_source_url', (row) => text(row.current_player_source_url)],
  ['created_at', (row) => utcTimestamp(row.created_at)],
];
const GAME_COLUMNS = [
  ['app_id', (row) => integer(row.app_id)],
  ['name', (row) => text(row.name)],
  ['category', (row) => text(row.category)],
  ['current_players', (row) => integer(row.current_players)],
  ['daily_peak', (row) => integer(row.daily_peak)],
  ['all_time_peak', (row) => integer(row.all_time_peak)],
  ['steam_daily_rank', (row) => text(row.steam_daily_rank)],
  ['top_seller_rank', (row) => text(row.top_seller_rank)],
  ['twitch_viewers', (row) => integer(row.twitch_viewers)],
  ['review_summary', (row) => text(row.review_summary)],
  ['source_url', (row) => text(row.source_url)],
];

const topUpFrom = getArg('--top-up');

if (topUpFrom) {
  const outPath = getArg('--out');

  if (!outPath) {
    console.error('Pass --out <file.sql> with --top-up.');
    process.exit(2);
  }

  const { sql, snapshots, games } = await buildTopUp(lastHourOf(topUpFrom));
  writeFileSync(outPath, sql);
  console.log(`Wrote ${outPath}: ${snapshots} captures and ${games} games after ${lastHourOf(topUpFrom)}.`);
} else {
  const checkPath = getArg('--check');
  const lastHour = checkPath ? lastHourOf(checkPath) : undefined;

  await writeOrCheckDataMigration(() => buildDataMigration(lastHour));

  if (checkPath) {
    await reportLaterHours(lastHour);
  }
}

/** Every capture up to `lastHour`, or up to the latest one when it is undefined. */
async function buildDataMigration(lastHour) {
  const db = createTursoClient();

  try {
    const until = lastHour ?? (await selectRows(db, 'SELECT max(capture_bucket) AS hour FROM game_stat_snapshots'))[0].hour;
    const snapshots = await selectRows(
      db,
      'SELECT * FROM game_stat_snapshots WHERE capture_bucket <= ? ORDER BY id',
      [until],
    );
    const games = await selectRows(
      db,
      `SELECT g.* FROM game_stat_snapshot_games g
        JOIN game_stat_snapshots s ON s.id = g.snapshot_id
        WHERE s.capture_bucket <= ? ORDER BY g.id`,
      [until],
    );

    return [
      '-- Game stats copied from Turso (issue 109). Generated by scripts/export-turso-game-stats.mjs; do not edit.',
      `-- ${snapshots.length} captures and ${games.length} games, Turso's ids kept.`,
      `-- Last hour copied: ${until}`,
      '--',
      '-- Safe to run twice: a row that already exists is left alone. Turso keeps capturing every hour',
      '-- until the merge; the script\'s --top-up copies those later hours.',
      '',
      ...insertStatements('public.game_stat_snapshots', [['id', (row) => integer(row.id)], ...SNAPSHOT_COLUMNS], snapshots),
      ...insertStatements(
        'public.game_stat_snapshot_games',
        [['id', (row) => integer(row.id)], ['snapshot_id', (row) => integer(row.snapshot_id)], ...GAME_COLUMNS],
        games,
      ),
      // The copied rows carry Turso's ids, so both sequences must continue after them.
      "select setval(pg_get_serial_sequence('public.game_stat_snapshots', 'id'), (select coalesce(max(id), 0) + 1 from public.game_stat_snapshots), false);",
      "select setval(pg_get_serial_sequence('public.game_stat_snapshot_games', 'id'), (select coalesce(max(id), 0) + 1 from public.game_stat_snapshot_games), false);\n",
    ].join('\n');
  } finally {
    db.close();
  }
}

// Rows are matched to their capture by hour, not by Turso's id, which Supabase may already use.
async function buildTopUp(lastHour) {
  const db = createTursoClient();

  try {
    const snapshots = await selectRows(
      db,
      'SELECT * FROM game_stat_snapshots WHERE capture_bucket > ? ORDER BY capture_bucket',
      [lastHour],
    );
    const games = await selectRows(
      db,
      `SELECT s.capture_bucket, g.* FROM game_stat_snapshot_games g
        JOIN game_stat_snapshots s ON s.id = g.snapshot_id
        WHERE s.capture_bucket > ? ORDER BY s.capture_bucket, g.app_id`,
      [lastHour],
    );
    const gameStatements = [];

    for (let start = 0; start < games.length; start += ROWS_PER_STATEMENT) {
      const values = games
        .slice(start, start + ROWS_PER_STATEMENT)
        .map((row) => `  (${[utcTimestamp(row.capture_bucket), ...GAME_COLUMNS.map(([, literal]) => literal(row))].join(', ')})`);
      const names = GAME_COLUMNS.map(([name]) => name);

      gameStatements.push(
        `insert into public.game_stat_snapshot_games (snapshot_id, ${names.join(', ')})\n` +
          `select s.id, ${names.map((name) => `v.${name}`).join(', ')}\nfrom (values\n${values.join(',\n')}\n` +
          `) as v (capture_bucket, ${names.join(', ')}), public.game_stat_snapshots s\n` +
          'where s.capture_bucket = v.capture_bucket\n' +
          'on conflict (snapshot_id, app_id) do nothing;\n',
      );
    }

    const sql = [
      `-- Game stat captures Turso took after ${lastHour}, generated by scripts/export-turso-game-stats.mjs --top-up.`,
      `-- ${snapshots.length} captures and ${games.length} games. Safe to apply twice.`,
      '',
      ...insertStatements('public.game_stat_snapshots', SNAPSHOT_COLUMNS, snapshots),
      ...gameStatements,
    ].join('\n');

    return { sql, snapshots: snapshots.length, games: games.length };
  } finally {
    db.close();
  }
}

async function reportLaterHours(lastHour) {
  const db = createTursoClient();

  try {
    const [{ hours }] = await selectRows(
      db,
      'SELECT count(*) AS hours FROM game_stat_snapshots WHERE capture_bucket > ?',
      [lastHour],
    );

    console.log(`Turso has ${hours} later hour(s) after ${lastHour}; copy them after the merge with --top-up.`);
  } finally {
    db.close();
  }
}

function lastHourOf(path) {
  const match = LAST_HOUR_LINE.exec(readFileSync(path, 'utf8'));

  if (!match) {
    console.error(`${path} has no "-- Last hour copied:" line; it is not a game stats data migration.`);
    process.exit(2);
  }

  return match[1];
}

function getArg(name) {
  const index = process.argv.indexOf(name);

  return index === -1 ? undefined : process.argv[index + 1];
}
