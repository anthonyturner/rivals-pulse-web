// One-off bridge from Turso to Supabase for the home page tables (issue 107). It writes the SQL that
// `npx supabase db push` applies, so the copy needs no Supabase service key. Issue 110 deletes
// this file together with the rest of Turso.
//
//   node scripts/export-turso-home-content.mjs --out supabase/migrations/<version>_home_content_data.sql
//   node scripts/export-turso-home-content.mjs --check supabase/migrations/<version>_home_content_data.sql
//
// The home news cron rewrites Turso every day at 03:00 UTC, so run `--check` just before the push
// and regenerate with `--out` if it fails.
import { createTursoClient } from './turso-client.mjs';
import {
  insertStatements,
  integer,
  json,
  selectRows,
  text,
  utcTimestamp,
  writeOrCheckDataMigration,
} from './turso-data-migration.mjs';

// The home news sync's snapshot of the official site; the other sources belong to issue 106.
const HOME_SOURCE_KEY = 'official-marvel-rivals-home';

await writeOrCheckDataMigration(buildSql);

async function buildSql() {
  const db = createTursoClient();

  try {
    const portals = await selectRows(db, 'SELECT * FROM home_portals ORDER BY id');
    const blocks = await selectRows(db, 'SELECT * FROM home_content_blocks ORDER BY content_key');
    const sources = await selectRows(db, 'SELECT * FROM external_sources WHERE source_key = ?', [HOME_SOURCE_KEY]);

    return [
      '-- Home page data copied from Turso (issue 107). Generated by scripts/export-turso-home-content.mjs; do not edit.',
      `-- ${portals.length} portals, ${blocks.length} content blocks, ${sources.length} source.`,
      '--',
      '-- Safe to run twice: a row that already exists is left alone, so a re-run can never',
      '-- overwrite what the home news sync has written since.',
      '',
      ...insertStatements('public.home_portals', [
        ['id', (row) => integer(row.id)],
        ['title', (row) => text(row.title)],
        ['description', (row) => text(row.description)],
        ['path', (row) => text(row.path)],
        ['image', (row) => text(row.image)],
        ['sort_order', (row) => integer(row.sort_order)],
        ['raw_json', (row) => json(row.raw_json)],
        ['updated_at', (row) => utcTimestamp(row.updated_at)],
      ], portals),
      ...insertStatements('public.home_content_blocks', [
        ['content_key', (row) => text(row.content_key)],
        // A JSON null is stored as SQL null, the way the sync's writes through PostgREST store it.
        ['payload', (row) => (JSON.parse(row.payload_json) === null ? 'null' : json(row.payload_json))],
        ['updated_at', (row) => utcTimestamp(row.updated_at)],
      ], blocks),
      ...insertStatements('public.external_sources', [
        ['source_key', (row) => text(row.source_key)],
        ['source_name', (row) => text(row.source_name)],
        ['url', (row) => text(row.url)],
        ['payload', (row) => json(row.payload_json)],
        ['fetched_at', (row) => utcTimestamp(row.fetched_at)],
        ['status', (row) => text(row.status)],
        ['error', (row) => text(row.error)],
      ], sources),
      // The copied portals carry Turso's ids, so the sequence must continue after them.
      "select setval(pg_get_serial_sequence('public.home_portals', 'id'), (select coalesce(max(id), 0) + 1 from public.home_portals), false);\n",
    ].join('\n');
  } finally {
    db.close();
  }
}
