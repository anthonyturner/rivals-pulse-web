// One-off bridge from Turso to Supabase for the hero tables (issue 105). It writes the SQL that
// `npx supabase db push` applies, so the copy needs no Supabase service key. Issue 110 deletes
// this file together with the rest of Turso.
//
//   node scripts/export-turso-heroes.mjs --out supabase/migrations/<version>_hero_content_data.sql
//   node scripts/export-turso-heroes.mjs --check supabase/migrations/<version>_hero_content_data.sql
//
// `--check` exits 1 when Turso has changed since the file was written; run it just before the push.
import { readFileSync, writeFileSync } from 'node:fs';

import { createTursoClient } from './turso-client.mjs';

// The hero syncs' snapshots in `external_sources`; the other sources belong to later slices.
const HERO_SOURCE_KEYS = ['official-heroes', 'fandom-heroes', 'nerfpool-s9-week1'];
const ROWS_PER_STATEMENT = 25;

const outPath = getPathArg('--out');
const checkPath = getPathArg('--check');

if (Boolean(outPath) === Boolean(checkPath)) {
  console.error('Pass exactly one of --out <file> or --check <file>.');
  process.exit(2);
}

const sql = await buildSql();

if (outPath) {
  writeFileSync(outPath, sql);
  console.log(`Wrote ${outPath}.`);
} else if (readFileSync(checkPath, 'utf8') === sql) {
  console.log('Turso matches the data migration.');
} else {
  console.error('Turso has changed since the data migration was written. Regenerate it with --out.');
  process.exit(1);
}

async function buildSql() {
  const db = createTursoClient();

  try {
    const heroes = await select(db, 'SELECT * FROM heroes ORDER BY id');
    const listItems = await select(db, 'SELECT * FROM hero_list_items ORDER BY id');
    const abilities = await select(db, 'SELECT * FROM hero_abilities ORDER BY id');
    const sources = await select(
      db,
      `SELECT * FROM external_sources WHERE source_key IN (${HERO_SOURCE_KEYS.map(() => '?').join(', ')}) ORDER BY source_key`,
      HERO_SOURCE_KEYS,
    );

    return [
      '-- Hero data copied from Turso (issue 105). Generated by scripts/export-turso-heroes.mjs; do not edit.',
      `-- ${heroes.length} heroes, ${listItems.length} list items, ${abilities.length} abilities, ${sources.length} sources.`,
      '--',
      '-- Safe to run twice: a row that already exists is left alone, so a re-run can never',
      '-- overwrite what the syncs have written since.',
      '',
      ...insertStatements('public.hero_content', [
        ['id', (row) => text(row.id)],
        ['name', (row) => text(row.name)],
        ['role', (row) => text(row.role)],
        ['difficulty', (row) => integer(row.difficulty)],
        ['summary', (row) => text(row.summary)],
        ['playstyle', (row) => text(row.playstyle)],
        ['image_url', (row) => text(row.image_url)],
        ['raw_json', (row) => json(row.raw_json)],
        ['updated_at', (row) => utcTimestamp(row.updated_at)],
      ], heroes),
      ...insertStatements('public.hero_list_items', [
        ['id', (row) => integer(row.id)],
        ['hero_id', (row) => text(row.hero_id)],
        ['item_type', (row) => text(row.item_type)],
        ['value', (row) => text(row.value)],
        ['sort_order', (row) => integer(row.sort_order)],
      ], listItems),
      ...insertStatements('public.hero_abilities', [
        ['id', (row) => integer(row.id)],
        ['hero_id', (row) => text(row.hero_id)],
        ['kit_role', (row) => text(row.kit_role)],
        ['kit_label', (row) => text(row.kit_label)],
        ['name', (row) => text(row.name)],
        ['ability_type', (row) => text(row.ability_type)],
        ['description', (row) => text(row.description)],
        ['technical_details', (row) => json(row.technical_details_json)],
        ['sort_order', (row) => integer(row.sort_order)],
      ], abilities),
      ...insertStatements('public.external_sources', [
        ['source_key', (row) => text(row.source_key)],
        ['source_name', (row) => text(row.source_name)],
        ['url', (row) => text(row.url)],
        ['payload', (row) => json(row.payload_json)],
        ['fetched_at', (row) => text(row.fetched_at)],
        ['status', (row) => text(row.status)],
        ['error', (row) => text(row.error)],
      ], sources),
      // The copied rows carry Turso's ids, so the sequences must continue after them.
      ...['hero_list_items', 'hero_abilities'].map(
        (table) => `select setval(pg_get_serial_sequence('public.${table}', 'id'), (select coalesce(max(id), 0) + 1 from public.${table}), false);\n`,
      ),
    ].join('\n');
  } finally {
    db.close();
  }
}

async function select(db, sql, args = []) {
  const result = await db.execute(sql, args);

  return result.rows.map((row) => Object.fromEntries(result.columns.map((column) => [column, row[column]])));
}

function insertStatements(table, columns, rows) {
  const statements = [];

  for (let start = 0; start < rows.length; start += ROWS_PER_STATEMENT) {
    const values = rows
      .slice(start, start + ROWS_PER_STATEMENT)
      .map((row) => `  (${columns.map(([, literal]) => literal(row)).join(', ')})`);

    statements.push(
      `insert into ${table} (${columns.map(([name]) => name).join(', ')}) values\n${values.join(',\n')}\non conflict do nothing;\n`,
    );
  }

  return statements;
}

function text(value) {
  return value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
}

function integer(value) {
  if (!Number.isInteger(Number(value))) {
    throw new Error(`Expected an integer but found ${JSON.stringify(value)}.`);
  }

  return String(Number(value));
}

// Throws on malformed JSON here instead of during the push.
function json(value) {
  JSON.parse(value);

  return `${text(value)}::jsonb`;
}

// SQLite's CURRENT_TIMESTAMP is UTC but carries no zone.
function utcTimestamp(value) {
  return `'${String(value).replaceAll("'", "''")}+00'::timestamptz`;
}

function getPathArg(name) {
  const index = process.argv.indexOf(name);

  return index === -1 ? undefined : process.argv[index + 1];
}
